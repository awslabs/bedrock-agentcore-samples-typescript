// This file will check cdk nag results and add appropriate configuration to pass nag checks

import { Aspects, Stack } from 'aws-cdk-lib';
import { AwsSolutionsChecks, NagSuppressions } from 'cdk-nag';
import { CfnFunction } from 'aws-cdk-lib/aws-lambda';
import { CfnUserPool, CfnIdentityPool } from 'aws-cdk-lib/aws-cognito';
import { CfnGraphQLApi } from 'aws-cdk-lib/aws-appsync';
import { CfnRole, CfnPolicy } from 'aws-cdk-lib/aws-iam';
import { CfnTable } from 'aws-cdk-lib/aws-dynamodb';
import { CfnBucket } from 'aws-cdk-lib/aws-s3';

/**
 * Apply CDK Nag checks to a stack and add necessary suppressions
 * @param stack The CDK stack to apply nag checks to
 */
export function applyCdkNag(stack: Stack): void {
  // Apply AWS Solutions checks
  Aspects.of(stack).add(new AwsSolutionsChecks({ verbose: true }));

  // Traverse the stack and apply suppressions
  applyStackSuppressions(stack);
}

/**
 * Traverse the CDK tree and apply suppressions to resources
 * @param stack The CDK stack to traverse
 */
function applyStackSuppressions(stack: Stack): void {
  // Apply stack-level suppressions
  NagSuppressions.addStackSuppressions(stack, [
    {
      id: 'AwsSolutions-IAM4',
      reason: 'AWS managed policies are acceptable for this use case. Amplify-generated roles use AWS managed policies.',
    },
    {
      id: 'AwsSolutions-IAM5',
      reason: 'Wildcard permissions are required for dynamic resources and Amplify-generated policies. AppSync requires wildcards for GraphQL type operations.',
      appliesTo: [
        'Resource::*',
        'Resource::<amplifyDataGraphQLAPI42A6FA33.ApiId>/types/*',
        {
          regex: '/^Resource::.*\\*$/g',
        },
      ],
    },
    {
      id: 'AwsSolutions-COG7',
      reason: 'Cognito identity pool allows unauthenticated access for specific use cases where guest access is required.',
    },
    {
      id: 'AwsSolutions-S10',
      reason: 'S3 bucket SSL requirement is handled by bucket policies. Amplify-generated buckets have appropriate security configurations.',
    },
  ]);

  // Apply suppressions to Amplify Data policies by path pattern
  const amplifyDataPolicyPaths = [
    '/data/amplifyData/AuthRolePolicy01/Resource',
    '/data/amplifyData/AuthRolePolicy02/Resource',
    '/data/amplifyData/UnauthRolePolicy01/Resource',
    '/data/amplifyData/UnauthRolePolicy02/Resource',
  ];

  amplifyDataPolicyPaths.forEach(policyPath => {
    try {
      NagSuppressions.addResourceSuppressionsByPath(
        stack,
        stack.stackName + policyPath,
        [
          {
            id: 'AwsSolutions-IAM5',
            reason: 'Amplify Data policies require wildcard permissions for AppSync GraphQL type operations. This is necessary for dynamic GraphQL schema types and is generated by AWS Amplify.',
          },
        ]
      );
    } catch (e) {
      // Path might not exist, continue
    }
  });

  // Apply suppression to Cognito Identity Pool
  try {
    NagSuppressions.addResourceSuppressionsByPath(
      stack,
      stack.stackName + '/auth/amplifyAuth/IdentityPool',
      [
        {
          id: 'AwsSolutions-COG7',
          reason: 'Cognito identity pool allows unauthenticated access for specific application features that require guest access. This is intentional for the application use case.',
        },
      ]
    );
  } catch (e) {
    // Path might not exist, continue
  }

  // Traverse all resources in the stack
  stack.node.findAll().forEach((construct) => {
    // Lambda Function suppressions
    if (construct.node.defaultChild instanceof CfnFunction) {
      applyLambdaSuppressions(stack, construct.node.path);
    }

    // Cognito User Pool suppressions
    if (construct.node.defaultChild instanceof CfnUserPool) {
      applyCognitoSuppressions(stack, construct.node.path);
    }

    // Cognito Identity Pool suppressions
    if (construct.node.defaultChild instanceof CfnIdentityPool) {
      applyCognitoIdentityPoolSuppressions(stack, construct.node.path);
    }

    // AppSync GraphQL API suppressions
    if (construct.node.defaultChild instanceof CfnGraphQLApi) {
      applyAppSyncSuppressions(stack, construct.node.path);
    }

    // IAM Role suppressions
    if (construct.node.defaultChild instanceof CfnRole) {
      applyIAMRoleSuppressions(stack, construct.node.path);
    }

    // IAM Policy suppressions - including Amplify Data policies
    if (construct.node.defaultChild instanceof CfnPolicy) {
      applyIAMPolicySuppressions(stack, construct.node.path);
      
      // Additional suppressions for Amplify Data Auth/Unauth policies
      const pathLower = construct.node.path.toLowerCase();
      if (pathLower.includes('amplifydata') && 
          (pathLower.includes('authrolepolicy') || pathLower.includes('unauthrolepolicy'))) {
        applyAmplifyDataPolicySuppressions(stack, construct.node.path);
      }
    }

    // DynamoDB Table suppressions
    if (construct.node.defaultChild instanceof CfnTable) {
      applyDynamoDBSuppressions(stack, construct.node.path);
    }

    // S3 Bucket suppressions
    if (construct.node.defaultChild instanceof CfnBucket) {
      applyS3Suppressions(stack, construct.node.path);
    }
    
    // S3 Bucket Policy suppressions (for AmplifyCodegenAssets)
    if (construct.node.path.includes('AmplifyCodegenAssets') && 
        construct.node.path.includes('Policy')) {
      NagSuppressions.addResourceSuppressionsByPath(
        stack,
        construct.node.path,
        [
          {
            id: 'AwsSolutions-S10',
            reason: 'Amplify Codegen Assets bucket policy is managed by Amplify. SSL/TLS requirements are handled appropriately.',
          },
        ]
      );
    }
  });
}

